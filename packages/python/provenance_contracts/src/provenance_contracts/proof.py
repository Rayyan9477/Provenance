class BeliefProof(Contract):
    """One proposition, its current version, its grounding, and its lineage.

    This model is the reason the three-term vocabulary exists. ``grounding``
    answers "why do you believe this"; ``lineage`` answers "what did you
    believe before, and what changed your mind".
    """

    belief_id: uuid.UUID
    subject_type: SubjectType
    subject_id: uuid.UUID
    subject_label: Annotated[str, StringConstraints(max_length=200)]
    predicate: SafeIdentifier
    current_version: BeliefVersionProof
    grounding: tuple[GroundingEdgeProof, ...] = Field(default=(), max_length=30)
    lineage: tuple[LineageEntry, ...] = Field(default=(), max_length=30)
    derivation: DerivationTrace | None = None

    @model_validator(mode="after")
    def _require_grounding(self) -> BeliefProof:
        """The read-side grounding invariant, checked at render time.

        If this ever fires in production it means a canonical belief exists
        that the system cannot justify, which is a data-integrity incident, not
        a rendering bug. Failing loudly here is the point.
        """
        if self.current_version.epistemic_status is EpistemicStatus.RETRACTED:
            return self
        if self.derivation is not None:
            return self
        supports = [e for e in self.grounding if e.relation is SupportRelation.SUPPORTS]
        if not supports:
            raise ValueError(
                f"belief {self.belief_id} ({self.predicate}) is canonical but "
                "UNGROUNDED: no SUPPORTS edge and no derivation"
            )
        return self

    @model_validator(mode="after")
    def _lineage_is_ordered_and_consistent(self) -> BeliefProof:
        versions = [entry.version_no for entry in self.lineage]
        if versions != sorted(versions):
            raise ValueError("lineage must be ordered oldest-first")
        if len(set(versions)) != len(versions):
            raise ValueError("duplicate version_no in lineage")
        if self.lineage:
            # Order matters, and it is the reverse of the order section 14
            # prints. A chain that stops short of the current version -- the
            # `stale_lineage` fixture in section 20.8 -- trips *both* checks,
            # and section 20.8 asserts the open-ends message. With section 14's
            # order the newest-entry check fires first and that printed test
            # can never see the message it asserts. Both checks are kept and
            # both stay reachable; only which one speaks first changed.
            open_ends = [e for e in self.lineage if e.superseded_by_version_id is None]
            if len(open_ends) != 1:
                raise ValueError("exactly one lineage entry may be un-superseded (the current one)")
            if self.current_version.version_no != max(versions):
                raise ValueError("current_version must be the newest entry in the lineage chain")
        return self

    @model_validator(mode="after")
    def _successor_pointers_agree(self) -> BeliefProof:
        """``superseded_by_version_no`` must name the version it points at.

        Two spellings of one pointer is two chances to drift; this is where
        they are made to agree, so the rendered chain and the id chain cannot
        tell different stories.
        """
        by_id: dict[uuid.UUID, int] = {
            entry.belief_version_id: entry.version_no for entry in self.lineage
        }
        by_id.setdefault(self.current_version.belief_version_id, self.current_version.version_no)
        for entry in self.lineage:
            if entry.superseded_by_version_no is None or entry.superseded_by_version_id is None:
                continue
            known = by_id.get(entry.superseded_by_version_id)
            if known is not None and known != entry.superseded_by_version_no:
                raise ValueError(
                    f"version {entry.version_no} names successor "
                    f"{entry.superseded_by_version_no} but the id it carries is "
                    f"version {known}"
                )
        return self

    @property
    def is_disputed(self) -> bool:
        return self.current_version.epistemic_status is EpistemicStatus.DISPUTED

    @property
    def contradicting_edges(self) -> tuple[GroundingEdgeProof, ...]:
        return tuple(e for e in self.grounding if e.relation is SupportRelation.CONTRADICTS)


