class LineageEntry(Contract):
    """One link in the version chain, with the reason it was replaced.

    Lineage without reasons is a changelog. Lineage with reason codes is an
    argument, which is what the user needs when a counterparty disputes it.

    ``superseded_by_version_no`` is the human-facing pointer the proof renders;
    ``superseded_by_version_id`` is the machine one. See recorded deviation 1.
    """

    belief_version_id: uuid.UUID
    version_no: Annotated[int, Field(ge=1)]
    value_json: JsonValue
    epistemic_status: EpistemicStatus
    valid_from: UtcDatetime | None = None
    valid_to: UtcDatetime | None = None
    recorded_at: UtcDatetime
    superseded_at: UtcDatetime | None = None
    superseded_by_version_id: uuid.UUID | None = None
    superseded_by_version_no: Annotated[int, Field(ge=2)] | None = None
    supersession_reason_code: ReasonCode | None = None
    kernel_decision_id: uuid.UUID

    @model_validator(mode="after")
    def _supersession_is_explained(self) -> LineageEntry:
        superseded = self.superseded_by_version_id is not None
        if superseded and self.supersession_reason_code is None:
            raise ValueError(f"version {self.version_no} was superseded without a reason code")
        if superseded and self.superseded_at is None:
            raise ValueError("a superseded version must record superseded_at")
        if self.superseded_by_version_no is not None:
            if not superseded:
                raise ValueError(
                    "superseded_by_version_no without superseded_by_version_id names "
                    "a successor the chain cannot resolve"
                )
            if self.superseded_by_version_no <= self.version_no:
                raise ValueError(
                    f"version {self.version_no} cannot be superseded by version "
                    f"{self.superseded_by_version_no}; the chain only moves forward"
                )
        validate_half_open(self.valid_from, self.valid_to)
        return self

    @property
    def is_current(self) -> bool:
        """True for the one open-ended entry: the version standing today."""
        return self.superseded_by_version_id is None


