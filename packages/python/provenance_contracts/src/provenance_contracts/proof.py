"""The deterministic explanation read model.

Assembled by the control plane from committed rows only. Nothing here is
generated by a model, and no field accepts model prose.

Authority
---------
- ``specs/11_CONTRACTS.md`` section 14, whose code this module implements, and
  section 20.8.
- ``EXECUTION/70_TASK_PLAN.md`` T1.6, third sub-task, and section 2.3 -- the
  three-term vocabulary.

Grounding and lineage are two fields, never one
------------------------------------------------
:class:`BeliefProof` carries **``grounding``** -- the ``SUPPORTS`` /
``CONTRADICTS`` / ``QUALIFIES`` edge set, answering "why do you believe this"
-- and **``lineage``** -- the version chain, answering "what did you believe
before, and what changed your mind". They are separate fields under exactly
those two names and are never conflated: a changelog is not an argument, and
an argument is not a changelog.

Recorded deviations from section 14
-----------------------------------
1. **``LineageEntry.superseded_by_version_no`` is added**, optional. Section 14
   declares only ``superseded_by_version_id``, but ``EXECUTION/70_TASK_PLAN.md``
   T1.6 asks for the chain "with ``superseded_by_version_no``", and the wire
   shape in ``specs/15_API_SPEC.md``, the lineage table in
   ``frontend/30_UX_SPEC.md``, and the ``G8`` acceptance query in
   ``quality/23_PHASE_GATES.md`` all read ``superseded_by_version_no``. Both are
   carried so neither authority is contradicted. It is optional rather than
   required because section 20.8's own printed fixtures construct a superseded
   entry without it; when it *is* present it must be greater than
   ``version_no`` and must agree with the entry it points at.

2. **``StateTransitionProof`` is exported.** Section 14 defines the class and
   uses it as the type of ``StateProof.transitions``, but omits it from its
   ``__all__``. That is a spec typo; a field type that cannot be imported is
   not usable. Reported, and exported here.
"""

